/**
 * The `exportVendorMavenRepository` task: writes every vendor module and category bundle as a Maven repository.
 *
 * Each module gets its jar, a `pom.xml`, Gradle module metadata and checksums, so the distribution can be uploaded to
 * any Maven repository (Nexus, Artifactory, a folder) and used without the consumer plugin.
 */
@CacheableTask
abstract class ExportVendorMavenRepositoryTask : DefaultTask() {
    /** The directory that holds the vendor jars. */
    @get:Internal
    abstract val vendorDir: DirectoryProperty

    /** Folders and files below [vendorDir] that are never scanned, see [VendorDistributorSettingsExtension.scanExcludes]. */
    @get:Input
    abstract val scanExcludes: ListProperty<String>

    /** The vendor jars that are exported. */
    @get:InputFiles
    @get:PathSensitive(PathSensitivity.RELATIVE)
    val vendorJars: FileTree
        get() = VendorJarScanner.jarTree(vendorDir, scanExcludes)

    /** The repository generated by `generateVendorIvyRepo`; its slim jars are exported too. */
    @get:InputDirectory
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val ivyDir: DirectoryProperty

    /** The module graph written by `resolveVendorModules`. */
    @get:InputFile
    @get:PathSensitive(PathSensitivity.NONE)
    abstract val dependencyGraphFile: RegularFileProperty

    /** The version of the distribution and of its bundles. */
    @get:Input
    abstract val versionString: Property<String>

    /** The group of the category bundles. */
    @get:Input
    abstract val bundleGroup: Property<String>

    /** The Maven repository, by default `build/vendor-maven-repo`. */
    @get:OutputDirectory
    abstract val outputDir: DirectoryProperty

    init {
        scanExcludes.convention(emptyList())
    }

    /** Writes [outputDir]. */
    @TaskAction
    fun export() {
        val out = outputDir.get().asFile
        out.deleteRecursively()
        out.mkdirs()
        val modules = VendorIvyDependencyMapper.loadGraph(dependencyGraphFile.get().asFile)
        val written = VendorMavenLayout.write(
            modules, vendorDir.get().asFile, ivyDir.get().asFile, out, versionString.get(), bundleGroup.get()
        )
        logger.lifecycle("Vendor Maven repository: {} module(s) and bundle(s) in {}", written, out)
    }
}

/**
 * The `publishVendorMavenRepository` task: uploads the repository of `exportVendorMavenRepository` to [url].
 *
 * Every file is sent with an HTTP `PUT` (the deploy request of Nexus, Artifactory and similar), or copied when [url] is
 * a `file:` URL. Configure it with `vendor.publish.url` and `vendor.publish.username`; the password is read from the
 * Gradle property `vendor.publish.password` or the environment variable `VENDOR_PUBLISH_PASSWORD`.
 */
@DisableCachingByDefault(because = "Uploads files to a remote repository")
abstract class PublishVendorMavenRepositoryTask : DefaultTask() {
    /** The repository written by `exportVendorMavenRepository`. */
    @get:InputDirectory
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val repositoryDir: DirectoryProperty

    /** The Maven repository to upload to, `https://...` or `file:...`. */
    @get:Input
    @get:Optional
    abstract val url: Property<String>

    /** The user name for [url]. */
    @get:Input
    @get:Optional
    abstract val username: Property<String>

    /** The password or token for [url]. */
    @get:Internal
    abstract val password: Property<String>

    /** Uploads every file of [repositoryDir]. */
    @TaskAction
    fun publish() {
        val target = url.orNull?.trimEnd('/')
            ?: throw GradleException(
                "publishVendorMavenRepository needs a target: set vendor.publish.url (and vendor.publish.username, with the " +
                    "password in the Gradle property vendor.publish.password or the environment variable VENDOR_PUBLISH_PASSWORD)."
            )
        val root = repositoryDir.get().asFile
        val files = root.walkTopDown().filter { it.isFile }.map { it.relativeTo(root).invariantSeparatorsPath to it }
            .sortedWith(compareBy({ it.first.substringAfterLast('/').startsWith("maven-metadata") }, { it.first }))
            .toList()
        val uri = URI(target)
        if (uri.scheme.equals("file", ignoreCase = true)) {
            val dir = File(uri)
            files.forEach { (path, file) -> file.copyTo(File(dir, path), overwrite = true) }
        } else {
            val client = HttpClient.newBuilder().connectTimeout(Duration.ofSeconds(30)).followRedirects(HttpClient.Redirect.NORMAL).build()
            val auth = username.orNull?.let { user ->
                "Basic " + Base64.getEncoder().encodeToString("$user:${password.orNull.orEmpty()}".toByteArray())
            }
            for ((path, file) in files) {
                val request = HttpRequest.newBuilder(URI("$target/$path"))
                    .timeout(Duration.ofMinutes(10))
                    .PUT(HttpRequest.BodyPublishers.ofFile(file.toPath()))
                    .apply { auth?.let { header("Authorization", it) } }
                    .build()
                val response = client.send(request, HttpResponse.BodyHandlers.ofString())
                if (response.statusCode() !in 200..299) {
                    throw GradleException(
                        "Uploading $path to $target failed with HTTP ${response.statusCode()}: ${response.body().take(300)}. " +
                            "A release repository usually refuses a version that is already there; publish a new vendor.version."
                    )
                }
            }
        }
        logger.lifecycle("Vendor Maven repository: {} file(s) published to {}", files.size, target)
    }
}

internal object VendorMavenLayout {
    fun write(modules: List<ResolvedModule>, vendorRoot: File, ivyRoot: File, out: File, version: String, bundleGroup: String): Int {
        val compileIds = modules.filter { it.compile }.mapTo(HashSet()) { it.moduleId }
        val versionsByArtifact = sortedMapOf<String, MutableSet<String>>()

        for (module in modules) {
            val dir = dir(out, module.groupId, module.artifactId, module.version)
            val base = "${module.artifactId}-${module.version}"
            val jar = File(dir, "$base.jar")
            File(vendorRoot, module.jarRelativePath).copyTo(jar, overwrite = true)
            val slimSource = File(ivyRoot, "${module.groupId}/$base/$base-slim.jar")
            val slim = if (module.compile && slimSource.isFile) File(dir, "$base-slim.jar").also { slimSource.copyTo(it, overwrite = true) } else null
            val apiDeps = module.apiDependsOn ?: if (module.compile) module.dependsOn.filter { it.moduleId in compileIds } else module.dependsOn
            val apiKeys = apiDeps.mapTo(HashSet()) { "${it.groupId}:${it.artifactId}" }

            File(dir, "$base.pom").writeText(pom(module.groupId, module.artifactId, module.version, null, module.dependsOn, apiKeys, module.licenses))
            File(dir, "$base.module").writeText(
                moduleJson(MavenComponent(module.groupId, module.artifactId, module.version, module.javaVersion), MavenVariant(slim ?: jar, apiDeps), MavenVariant(jar, module.dependsOn))
            )
            versionsByArtifact.getOrPut("${module.groupId}:${module.artifactId}") { sortedSetOf() } += module.version
        }

        val bundles = modules.filter { it.pluginIds.isEmpty() }
            .flatMap { module -> module.categories.map { it to module } }
            .groupBy({ it.first }, { it.second })
            .toSortedMap()
        for ((category, items) in bundles) {
            val dir = dir(out, bundleGroup, category, version)
            val deps = items.sortedBy { it.moduleId }.map { ResolvedDep(it.moduleId, it.groupId, it.artifactId, it.version) }
            val api = deps.filter { it.moduleId in compileIds }
            val apiKeys = api.mapTo(HashSet()) { "${it.groupId}:${it.artifactId}" }
            File(dir, "$category-$version.pom").writeText(pom(bundleGroup, category, version, "pom", deps, apiKeys, emptyList()))
            File(dir, "$category-$version.module").writeText(moduleJson(MavenComponent(bundleGroup, category, version, null), MavenVariant(null, api), MavenVariant(null, deps)))
            versionsByArtifact.getOrPut("$bundleGroup:$category") { sortedSetOf() } += version
        }

        for ((coordinate, versions) in versionsByArtifact.mapValues { (_, set) -> set.toList() }) {
            val (group, artifact) = coordinate.split(':')
            val dir = File(out, "${group.replace('.', '/')}/$artifact")
            File(dir, "maven-metadata.xml").writeText(metadata(group, artifact, versions.toList()))
        }
        out.walkTopDown().filter { it.isFile && it.extension !in CHECKSUMS.keys }.toList().forEach { file ->
            for ((extension, algorithm) in CHECKSUMS) File(file.path + ".$extension").writeText(digest(file, algorithm))
        }
        return modules.size + bundles.size
    }

    private val CHECKSUMS = linkedMapOf("md5" to "MD5", "sha1" to "SHA-1", "sha256" to "SHA-256", "sha512" to "SHA-512")

    private fun dir(out: File, group: String, artifact: String, version: String) =
        File(out, "${group.replace('.', '/')}/$artifact/$version").apply { mkdirs() }

    fun digest(file: File, algorithm: String): String {
        val digest = MessageDigest.getInstance(algorithm)
        file.inputStream().buffered(64 * 1024).use { input ->
            val buffer = ByteArray(64 * 1024)
            while (true) {
                val read = input.read(buffer)
                if (read < 0) break
                digest.update(buffer, 0, read)
            }
        }
        return digest.digest().joinToString("") { "%02x".format(it) }
    }

    private fun pom(
        group: String, artifact: String, version: String, packaging: String?,
        deps: List<ResolvedDep>, apiKeys: Set<String>, licenses: List<String>
    ): String = Templates.render(
        "pom.xml.vm",
        mapOf(
            "groupId" to group,
            "artifactId" to artifact,
            "version" to version,
            "packaging" to packaging,
            "licenses" to licenses,
            "dependencies" to deps.map { dep ->
                mapOf(
                    "group" to dep.groupId,
                    "module" to dep.artifactId,
                    "version" to dep.version,
                    "scope" to if ("${dep.groupId}:${dep.artifactId}" in apiKeys) "compile" else "runtime"
                )
            }
        )
    )

    internal class MavenComponent(val group: String, val artifact: String, val version: String, val javaVersion: Int?)

    internal class MavenVariant(val file: File?, val dependencies: List<ResolvedDep>)

    private fun moduleJson(component: MavenComponent, api: MavenVariant, runtime: MavenVariant): String {
        val group = component.group
        val artifact = component.artifact
        val version = component.version
        val javaVersion = component.javaVersion
        fun deps(list: List<ResolvedDep>) = list.map { mapOf("group" to it.groupId, "module" to it.artifactId, "version" to mapOf("requires" to it.version)) }
        fun files(file: File?) = listOfNotNull(file?.let {
            linkedMapOf(
                "name" to it.name, "url" to it.name, "size" to it.length(),
                "sha512" to digest(it, "SHA-512"), "sha256" to digest(it, "SHA-256"), "sha1" to digest(it, "SHA-1"), "md5" to digest(it, "MD5")
            )
        })
        fun variant(name: String, usage: String, file: File?, list: List<ResolvedDep>): Map<String, Any> {
            val attributes = linkedMapOf<String, Any>("org.gradle.category" to "library")
            if (file != null) attributes["org.gradle.libraryelements"] = "jar"
            attributes["org.gradle.usage"] = usage
            if (javaVersion != null) attributes["org.gradle.jvm.version"] = javaVersion
            val result = linkedMapOf<String, Any>("name" to name, "attributes" to attributes)
            if (file != null) result["files"] = files(file)
            result["dependencies"] = deps(list)
            return result
        }
        return JsonOutput.prettyPrint(
            JsonOutput.toJson(
                linkedMapOf(
                    "formatVersion" to "1.1",
                    "component" to linkedMapOf("group" to group, "module" to artifact, "version" to version),
                    "variants" to listOf(
                        variant("apiElements", "java-api", api.file, api.dependencies),
                        variant("runtimeElements", "java-runtime", runtime.file, runtime.dependencies)
                    )
                )
            )
        ) + "\n"
    }

    private fun metadata(group: String, artifact: String, versions: List<String>): String = Templates.render(
        "maven-metadata.xml.vm",
        mapOf("groupId" to group, "artifactId" to artifact, "latest" to versions.last(), "versions" to versions)
    )
}
