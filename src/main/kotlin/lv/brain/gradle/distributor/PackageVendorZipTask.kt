import org.gradle.api.file.DirectoryProperty
import org.gradle.api.file.FileTree
import org.gradle.api.file.RegularFileProperty
import org.gradle.api.provider.ListProperty
import org.gradle.api.provider.Property
import org.gradle.api.provider.Provider
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.InputDirectory
import org.gradle.api.tasks.InputFile
import org.gradle.api.tasks.InputFiles
import org.gradle.api.tasks.Internal
import org.gradle.api.tasks.Optional
import org.gradle.api.tasks.OutputFile
import org.gradle.api.tasks.PathSensitive
import org.gradle.api.tasks.PathSensitivity
import org.gradle.api.tasks.TaskAction
import org.gradle.work.DisableCachingByDefault

/**
 * The `packageVendorDistribution` and `packageVendorSlimDistribution` tasks: zip the vendor folder with its generated
 * Ivy repository.
 *
 * This ZIP is what the consumer plugin downloads and unpacks. It always holds the generated `ivy/` folder, the module
 * graph and every jar of a category; [includes] and [excludes] add the other files of the vendor folder.
 */
@DisableCachingByDefault(because = "Building the ZIP from its cached inputs is faster than storing and loading a ZIP of all vendor jars")
abstract class PackageVendorZipTask : DefaultTask() {
    /** The directory that holds the vendor jars. */
    @get:Internal
    abstract val vendorDir: DirectoryProperty

    /** Folders and files below [vendorDir] that are never packaged, see [VendorDistributorSettingsExtension.scanExcludes]. */
    @get:Input
    abstract val scanExcludes: ListProperty<String>

    /** The jars below [vendorDir] that were scanned; those of a category are copied into the ZIP. */
    @get:InputFiles
    @get:PathSensitive(PathSensitivity.RELATIVE)
    val vendorJars: FileTree
        get() = VendorJarScanner.jarTree(vendorDir, scanExcludes)

    /** Ant-style patterns of further files of [vendorDir] to package; `*` alone means everything. */
    @get:Input
    abstract val includes: ListProperty<String>

    /** Ant-style patterns of files of [vendorDir] that are not packaged even when [includes] matches them. */
    @get:Input
    abstract val excludes: ListProperty<String>

    /** The files of [vendorDir] selected by [includes] and [excludes]. */
    @get:InputFiles
    @get:PathSensitive(PathSensitivity.RELATIVE)
    val includedFiles: FileTree
        get() {
            val name = vendorDir.get().asFile.name
            val included = ScanExcludes.zipPatterns(includes.get(), name)
            val excluded = ScanExcludes.zipPatterns(excludes.get(), name) + ScanExcludes.gradlePatterns(scanExcludes.get(), name)
            return vendorDir.asFileTree.matching {
                if (included.isEmpty()) exclude("**") else include(included)
                exclude(excluded)
            }
        }

    /** The repository generated by `generateVendorIvyRepo`. */
    @get:InputDirectory
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val ivyDir: DirectoryProperty

    /** The version of the distribution. */
    @get:Input
    @get:Optional
    abstract val versionString: Property<String>

    /** The module graph written by `resolveVendorModules`; every jar it lists is packaged. */
    @get:InputFile
    @get:PathSensitive(PathSensitivity.NONE)
    abstract val dependencyGraphFile: RegularFileProperty

    /** The bill of materials written by `generateVendorSbom`, packaged as `vendor-sbom.cdx.json`. */
    @get:InputFile
    @get:Optional
    @get:PathSensitive(PathSensitivity.NONE)
    abstract val sbomFile: RegularFileProperty

    /** The distribution, by default `build/distributions/vendor-sdk-<version>.zip` (`-slim.zip` for the slim one). */
    @get:OutputFile
    abstract val outputZip: RegularFileProperty

    /** The private key (PEM or base64 PKCS#8) that signs [outputZip]; without it no signature is written. */
    @get:Internal
    abstract val signingKey: Property<String>

    /** Identifies [signingKey] without revealing it. */
    @get:Input
    @get:Optional
    val signingKeyId: Provider<String>
        get() = signingKey.map { VendorSignature.keyId(it) }

    /** The signature of [outputZip], next to it as `<zip>.sig`, written when [signingKey] is set; consumers check it with `vendor.signing.publicKey`. */
    @get:OutputFile
    val signatureFile: File
        get() = File(outputZip.get().asFile.path + VendorSignature.SUFFIX)

    /** The SHA-256 of [outputZip] (`<hash>  <file name>`), next to it as `<zip>.sha256`; consumers check it with `vendor.sha256`. */
    @get:OutputFile
    val checksumFile: File
        get() = File(outputZip.get().asFile.path + ".sha256")

    init {
        scanExcludes.convention(emptyList())
        includes.convention(listOf("**"))
        excludes.convention(emptyList())
    }

    /** Writes [outputZip]. */
    @TaskAction
    fun packageZip() {
        val rootDir = vendorDir.get().asFile
        val graphFile = dependencyGraphFile.get().asFile
        val ivyRoot = ivyDir.get().asFile
        val modules = VendorIvyDependencyMapper.loadGraph(graphFile)

        val entries = sortedMapOf<String, File>()
        modules.map { it.jarRelativePath }.distinct().forEach { relativePath ->
            val jarFile = File(rootDir, relativePath)
            check(jarFile.isFile) { "Vendor jar listed in ${graphFile.name} no longer exists: $jarFile" }
            entries[relativePath] = jarFile
        }
        includedFiles.visit {
            if (!isDirectory) entries.putIfAbsent(relativePath.pathString, file)
        }
        val ivyEntries = ivyRoot.walkTopDown()
            .onEnter { !it.name.startsWith(".") }
            .filter { it.isFile && !it.name.startsWith(".") }
            .map { "${VendorJarScanner.IVY_DIR_NAME}/${it.relativeTo(ivyRoot).invariantSeparatorsPath}" to it }
            .sortedBy { it.first }
            .toList()

        val zipFile = outputZip.get().asFile
        zipFile.parentFile.mkdirs()

        ZipOutputStream(zipFile.outputStream().buffered(64 * 1024)).use { zos ->
            writeZipEntry(zos, GRAPH_ENTRY, graphFile)
            sbomFile.orNull?.asFile?.takeIf { it.isFile }?.let { writeZipEntry(zos, VendorSbom.FILE_NAME, it) }
            ivyEntries.forEach { (entryName, file) -> writeZipEntry(zos, entryName, file) }
            entries.filterKeys { it != GRAPH_ENTRY && it != VendorSbom.FILE_NAME }.forEach { (entryName, file) -> writeZipEntry(zos, entryName, file) }
        }
        checksumFile.writeText("${RawReferenceScanner.sha256(zipFile)}  ${zipFile.name}\n")
        val key = signingKey.orNull
        if (key == null) {
            java.nio.file.Files.deleteIfExists(signatureFile.toPath())
        } else {
            signatureFile.writeText(VendorSignature.sign(zipFile, VendorSignature.privateKey(key)) + "\n")
        }
        logger.info("Vendor distribution {}: {} file(s) besides ivy/", zipFile.name, entries.size)
    }

    private fun writeZipEntry(zos: ZipOutputStream, entryName: String, file: File) {
        val entry = ZipEntry(entryName).withFixedTime()
        if (entryName.substringAfterLast('.').lowercase() in COMPRESSED_EXTENSIONS) {
            val crc = java.util.zip.CRC32()
            file.inputStream().buffered(64 * 1024).use { input ->
                val buffer = ByteArray(64 * 1024)
                while (true) {
                    val read = input.read(buffer)
                    if (read < 0) break
                    crc.update(buffer, 0, read)
                }
            }
            entry.method = ZipEntry.STORED
            entry.size = file.length()
            entry.compressedSize = file.length()
            entry.crc = crc.value
        }
        zos.putNextEntry(entry)
        file.inputStream().buffered(64 * 1024).use { it.copyTo(zos) }
        zos.closeEntry()
    }

    private companion object {
        val COMPRESSED_EXTENSIONS = setOf("jar", "war", "ear", "zip", "gz", "tgz", "xz", "bz2", "7z", "png", "jpg", "jpeg", "gif")
        const val GRAPH_ENTRY = "module-dependencies.json"
    }
}
